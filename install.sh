# Progress, colors and the launch button need a terminal; logs get plain lines.
live=
if [ -t 1 ] && [ "${TERM:-dumb}" != dumb ] && ( : </dev/tty ) 2>/dev/null; then live=1; fi
if [ -n "$live" ] && [ -z "${NO_COLOR:-}" ]; then
  bold="$esc[1m" dim="$esc[2m" strike="$esc[9m" unstrike="$esc[29m" cap="$esc[7m"
  green="$esc[32m" yellow="$esc[33m" red="$esc[31m" off="$esc[0m" key=' ⏎ '
else
  bold= dim= strike= unstrike= cap= green= yellow= red= off= key='[⏎]'
fi

ok() { printf '  %s✓%s %s\n' "$green" "$off" "$1"; }
already() { printf '  %s✓ %s%s\n' "$dim" "$(msg '${message} (already done)' "$strike$1$unstrike")" "$off"; }
skipped() { printf '  %s– %s%s\n' "$dim" "$1" "$off"; }
warn() { printf '  %s!%s %s\n' "$yellow" "$off" "$1"; }
fail() {
  stop_progress
  printf '  %s✗ %s%s\n' "$red" "$1" "$off" >&2
  exit 1
}
home() { case $1 in "$HOME"/*) printf '~%s' "${1#"$HOME"}" ;; *) printf %s "$1" ;; esac; }
mb() { t=$((($1 + 50000) / 100000)); printf '%d.%d MB' $((t / 10)) $((t % 10)); }

stop_progress() {
  [ -n "$watcher" ] || return 0
  kill "$watcher" 2>/dev/null || true
  wait "$watcher" 2>/dev/null || true
  watcher=
  printf '\r%s[K' "$esc"
}
cleanup() {
  stop_progress
  [ -z "$tty_mode" ] || stty "$tty_mode" </dev/tty 2>/dev/null || true
  [ -z "$live" ] || printf '%s[?25h' "$esc"
  [ -z "$tmp" ] || rm -rf "$tmp"
}
interrupted() {
  [ -z "$live" ] || printf '\r%s%s\n' "${below:+$esc[${below}B}" ''
  exit 130
}

fetch() {
  curl --disable -fsSL --proto '=https' --proto-redir '=https' \
    --connect-timeout 10 --max-time 300 "$base/releases/$version/$1" -o "$tmp/$2" \
    2>"$tmp/error" || fail "$(msg 'Could not download ${file}: ${error}' "$1" "$(cat "$tmp/error")")"
}

# Redraws "↓ Downloading corgi  23.8 / 67.2 MB  ━━━━━━━━────────  35%" until killed.
progress() {
  download_label=$(msg 'Downloading corgi')
  while :; do
    got=0
    [ ! -f "$tmp/corgi" ] || got=$(($(wc -c <"$tmp/corgi")))
    [ "$got" -le "$size" ] || got=$size
    fill= rest= i=0
    while [ $i -lt 24 ]; do
      if [ $i -lt $((got * 24 / size)) ]; then fill="${fill}━"; else rest="${rest}─"; fi
      i=$((i + 1))
    done
    printf '\r%s[K  %s↓%s %s  %s / %s  %s%s%s%s%s%s  %d%%' "$esc" \
      "$green" "$off" "$download_label" "$(mb "$got")" "$(mb "$size")" "$green" "$fill" "$off" "$dim" "$rest" "$off" \
      $((got * 100 / size))
    sleep 0.1
  done
}

install_corgi() {
  for path in "$root" "$bin"; do
    case $path in /*) ;; *) fail "$(msg 'Install paths must be absolute: ${path}' "$path")" ;; esac
  done
  installed=
  [ ! -f "$root/current" ] || installed=$(cat "$root/current")
  # Release versions are fixed-width UTC timestamps, so they order as text.
  if [ -n "$installed" ] && ! LC_ALL=C expr "x$version" \> "x$installed" >/dev/null; then
    already "$(msg 'Downloaded corgi')"
    write_launcher
    if [ "$was" = same ]; then
      already "$(msg 'Installed corgi ${version} at ${path}' "$installed" "$(home "$bin")")"
    else
      already "$(msg 'Installed corgi ${version}' "$installed")"
      ok "$(msg 'Restored the launcher at ${path}' "$(home "$bin")")"
    fi
    return
  fi
  tmp=$(mktemp -d)
  ok "$(msg 'Staging in ${path}' "$(home "$tmp")")"

  start=$(date +%s)
  if [ -n "$live" ]; then
    progress &
    watcher=$!
    fetch "corgi-$target" corgi
    stop_progress
  else
    printf '  ↓ %s  %s\n' "$(msg 'Downloading corgi')" "$(mb "$size")"
    fetch "corgi-$target" corgi
  fi
  ok "$(msg 'Downloaded corgi  ${size} in ${seconds}s' "$(mb "$size")" "$(($(date +%s) - start))")"

  if command -v sha256sum >/dev/null 2>&1; then
    actual=$(sha256sum "$tmp/corgi" | cut -d ' ' -f 1)
  else
    actual=$(shasum -a 256 "$tmp/corgi" | cut -d ' ' -f 1)
  fi
  [ "$actual" = "$expected" ] || fail "$(msg 'Corgi checksum mismatch')"
  ok "$(msg 'Verified checksum')  ${dim}sha256 $(printf '%.12s' "$expected")…$off"

  # Corgi verifies the signed manifest and installs itself, or stages itself over
  # an older installation for the next launch to activate.
  fetch "$manifest" manifest.json
  chmod 700 "$tmp/corgi"
  "$tmp/corgi" __install "$root" "$tmp/manifest.json" </dev/null 2>"$tmp/error" ||
    fail "$(msg 'Could not install corgi: ${error}' "$(cat "$tmp/error")")"
  write_launcher
  if [ -z "$installed" ]; then
    remember_plugin
    case $was in
      other) ok "$(msg 'Installed corgi at ${path} (replaced the existing file)' "$(home "$bin")")" ;;
      *) ok "$(msg 'Installed corgi at ${path}' "$(home "$bin")")" ;;
    esac
    return
  fi
  [ "$was" = same ] || ok "$(msg 'Restored the launcher at ${path}' "$(home "$bin")")"
  if [ -f "$root/auto-off" ]; then
    ok "$(msg 'Staged the update from ${version}; automatic updates are off. Run corgi update to apply it.' "$installed")"
  else
    ok "$(msg 'Updated corgi from ${version}; it takes over when corgi next starts.' "$installed")"
  fi
}

# Installed by Omarchy's bar plugin, Corgi removes itself when the plugin is
# removed: it watches the folder recorded here, then runs this script's
# uninstall, kept beside it since the plugin's copy goes with the plugin.
# A Corgi installed before the plugin isn't its to remove.
remember_plugin() {
  plugin=${CORGI_INSTALL_PLUGIN:-}
  [ -n "$plugin" ] && [ -f "$plugin/manifest.json" ] && [ -f "$0" ] || return 0
  printf '%s\n' "$plugin" >"$root/plugin"
  cp "$0" "$root/uninstall.sh"
}

# Match the executable's physical path, including macOS's /tmp symlink.
physical_root() {
  (cd "$root" 2>/dev/null && pwd -P || printf '%s\n' "$root")
}
quote_root() {
  physical_root | sed "s/'/'\\\\''/g"
}

# Writes the launcher that runs the current release over whatever is at $bin,
# and sets was to what it found there: a launcher (same), nothing (missing) or
# something else (other). Uninstall recognizes the launcher by its exec line.
write_launcher() {
  mkdir -p "$dir"
  quoted=$(quote_root)
  quoted_bin=$(printf %s "$bin" | sed "s/'/'\\\\''/g")
  invalid_version=$(msg 'Invalid Corgi version' | sed "s/'/'\\\\''/g")
  removed=$(msg 'Removed ${path}' "$(home "$bin")" | sed "s/'/'\\\\''/g")
  cat >"$bin.new" <<EOF
#!/bin/sh
set -eu
root='$quoted'
# The install went away without it, as when Omarchy removes Corgi's plugin.
if [ ! -e "\$root/current" ]; then
  rm -f '$quoted_bin'
  printf '%s\n' '$removed' >&2
  exit 127
fi
v=\$(cat "\$root/current")
case "\$v" in ''|*[!0-9.a-fTZ-]*) printf '%s\n' '$invalid_version' >&2; exit 1;; esac
exec "\$root/releases/\$v/corgi" "\$@"
EOF
  chmod 755 "$bin.new"
  if [ ! -e "$bin" ]; then was=missing
  elif grep -qF 'exec "$root/releases/$v/corgi"' "$bin" 2>/dev/null; then was=same
  else was=other
  fi
  mv -f "$bin.new" "$bin"
  printf %s "$bin" >"$root/launcher"
}

# A yes/no question on the terminal; Enter or y says yes.
ask() {
  printf '  %s?%s %s %s[%s]%s' "$yellow" "$off" "$1" "$dim" "$(msg 'Enter/Y: yes · N/Esc: no')" "$off"
  stty -icanon min 1 time 0 </dev/tty
  while :; do
    case $(dd bs=1 count=1 </dev/tty 2>/dev/null | od -An -tx1 | tr -d ' \n') in
      0a|0d|59|79) reply=0; break ;;
      1b|4e|6e|71) reply=1; break ;;
    esac
  done
  stty icanon </dev/tty
  printf '\r%s[K' "$esc"
  return $reply
}

# Puts the default install directory on PATH for new shells.
setup_path() {
  [ "$bin" = "$HOME/.local/bin/corgi" ] || return 0
  case ":$PATH:" in *":$dir:"*)
    on_path=1
    already "$(msg 'Added ${path} to PATH' "$(home "$dir")")"
    return ;;
  esac
  if [ "${CORGI_UPDATE_PATH:-1}" = 0 ]; then
    skipped "$(msg 'Left PATH alone (CORGI_UPDATE_PATH=0)')"
    return
  fi
  line=$path_line
  login_rc= bash_profile=
  shell=${SHELL:-sh}
  case "${shell##*/}" in
    zsh) rc="${ZDOTDIR:-$HOME}/.zshrc" ;;
    bash)
      rc="$HOME/.bashrc"
      for file in "$HOME/.bash_profile" "$HOME/.bash_login" "$HOME/.profile"; do
        if [ -f "$file" ]; then login_rc=$file; break; fi
      done
      # macOS terminals start login shells, which skip ~/.bashrc without one of these.
      [ -n "$login_rc" ] || [ "$(uname -s)" != Darwin ] || bash_profile=1 ;;
    fish) rc=$fish_rc line=$fish_line ;;
    *) warn "$(msg 'Add ${path} to PATH to run corgi by name.' "$(home "$dir")")"; return ;;
  esac
  added= files=
  for file in "$rc" "$login_rc"; do
    [ -n "$file" ] || continue
    if [ -n "$files" ]; then files=$(msg '${first} and ${second}' "$files" "$(home "$file")")
    else files=$(home "$file"); fi
    if ! grep -qxF "$line" "$file" 2>/dev/null; then
      mkdir -p "$(dirname "$file")"
      printf '\n# Corgi\n%s\n' "$line" >>"$file"
      added=1
    fi
  done
  if [ -n "$added" ]; then
    ok "$(msg 'Added ${path} to PATH in ${files}' "$(home "$dir")" "$files")"
  else
    already "$(msg 'Added ${path} to PATH in ${files}' "$(home "$dir")" "$files")"
  fi
  if [ -n "$bash_profile" ]; then
    if [ -n "$live" ] && ask "$(msg 'Create ~/.bash_profile so macOS terminals load ~/.bashrc?')"; then
      printf 'if [ -f ~/.bashrc ]; then . ~/.bashrc; fi\n' >"$HOME/.bash_profile"
      ok "$(msg 'Created ~/.bash_profile to load ~/.bashrc')"
    else
      warn "$(msg 'macOS terminals skip ~/.bashrc until ~/.bash_profile loads it.')"
    fi
  fi
  # Running fish sessions share fish_user_paths, so this terminal gets it too.
  if [ "${shell##*/}" = fish ] && [ -x "$shell" ]; then
    "$shell" -c 'fish_add_path -- $argv' "$dir" </dev/null >/dev/null 2>&1 || true
    on_path=1
  fi
}

